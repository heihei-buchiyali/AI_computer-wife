#算数运算符：+ — * / // % **
print("10+4=",10+4) #加
print("10-4=",10-4) #减
print("10*4=",10*4) #乘
print("10/4=",10/4) #除
print("10//4=",10//4) #整除（结果取整数）
print("10%4=",10%4) #取余 （结果为余数）
print("10**4=",10**4)  #幂指数，10的4次方

#运算优先级
